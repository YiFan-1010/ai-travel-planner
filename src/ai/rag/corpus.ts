/** 取出某城市的全部语料 */
export function docsForCity(city: string): Doc[] {
  const key = city.trim();
  if (!key) return [];
  /* 用户可能写「杭州市」「杭州西湖区」，用包含关系匹配 */
  return CORPUS.filter((d) => key.includes(d.city) || d.city.includes(key));
}
