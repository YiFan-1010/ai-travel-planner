/**
 * 取出某城市可用的语料：该城市的条目 + 通用条目。
 *
 * 通用条目一定要带上。语料只覆盖 20 个城市，用户搜「洛阳」「泉州」时
 * 如果只按城市过滤，检索结果直接为空，RAG 在这类目的地面前等于不存在。
 */
export function docsForCity(city: string): Doc[] {
  const key = city.trim();
  const general = CORPUS.filter((d) => d.city === GENERIC_CITY);
  if (!key) return general;

  /* 用户可能写「杭州市」「杭州西湖区」，用包含关系匹配 */
  const local = CORPUS.filter(
    (d) => d.city !== GENERIC_CITY && (key.includes(d.city) || d.city.includes(key))
  );
  return local.concat(general);
}
